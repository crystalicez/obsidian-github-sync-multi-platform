const RISK = "accept-best-effort-power-loss-recovery-risk"
const TRANSACTION = /^[0-9a-f]{32}$/u

export interface V4FencedLiveCandidateStageInput {
  readonly readiness: V4FencedPrecommitReadinessInput
  readonly backup: V4FencedFrozenBackupContentInput
  /** Fresh unpredictable 128-bit per-attempt ID generated by the trusted caller. */
  readonly transactionId: string
}

export interface V4FencedLiveCandidateStageReport extends V4ReencryptionCutoverCandidateStageReport {
  readonly provenance: "two-full-current-destination-and-frozen-backup-proofs-bracketing-write"
}

export interface V4FencedLiveIntentStageReport extends Omit<V4FencedLiveCandidateStageReport, "status"> {
  readonly status: "production-namespace-intent-staged-uncommitted"
  readonly intentPath: string
}

/**
 * D224: the only composition here that can *derive* rather than accept the
 * D223 candidate contract. It is still a NON-AUTHORIZING staged candidate:
 * it DOES NOT create a committed Receipt, select an Index/branch or clear
 * the Sync Fence. Logical readback is NOT OS power-loss durability.
 *
 * Exactly ONE externally acquired initiating-device owner lease surrounds
 * D183 (complete Source/Shadow/Prepared/WAL and new-key Destination), D216
 * (complete old-key frozen Backup), D223 candidate persistence, and repeats
 * of both full proofs. Every inner tool borrows the same held lease.
 */
async function stageInternal(
  input: V4FencedLiveCandidateStageInput, persistIntent: false,
): Promise<V4FencedLiveCandidateStageReport>
async function stageInternal(
  input: V4FencedLiveCandidateStageInput, persistIntent: true,
): Promise<V4FencedLiveIntentStageReport>
async function stageInternal(
  input: V4FencedLiveCandidateStageInput, persistIntent: boolean,
): Promise<V4FencedLiveCandidateStageReport | V4FencedLiveIntentStageReport> {
  const readiness = input?.readiness
  const prepared = readiness?.prepared
  const full = readiness?.full
  const branches = full?.branches
  const shadow = full?.shadow
  const restart = prepared?.restart
  const backup = input?.backup
  const id = branches?.identity
  if (!prepared || !restart || !branches || !shadow?.remote || !backup || !id
    || typeof input.transactionId !== "string" || !TRANSACTION.test(input.transactionId)
    || /^0+$/u.test(input.transactionId)) {
    throw Error("D224 requires a prepared full Git migration and valid transaction ID.")
  }
  const holder = prepared.withExclusiveInitiatorLease
  const lease = restart.assertExclusiveInitiatorLease
  const adapter = restart.indexAdapter
  const wal = restart.wal
  const journal = restart.journal
  const key = prepared.journalKey
  const getSecret = restart.getSecret
  const destinationGithub = shadow.remote.github
  const frozenGithub = backup.backup?.github
  const readers = branches.readers
  if (!destinationGithub || !frozenGithub || !readers
    || typeof holder !== "function" || typeof lease !== "function"
    || !(key instanceof Uint8Array) || key.length !== 32
    || typeof getSecret !== "function"
    || typeof wal?.assertExclusiveStageLease !== "function"
    || typeof wal.assertBestEffortCheckpoint !== "function"
    || typeof journal?.assertHealthySnapshot !== "function"
    || typeof adapter?.read !== "function" || typeof adapter.exists !== "function"
    || typeof adapter.write !== "function" || typeof adapter.mkdir !== "function"
    || branches.acknowledgement !== RISK || restart.acknowledgement !== RISK
    || branches.withExclusiveInitiatorLease !== holder
    || branches.assertExclusiveInitiatorLease !== lease
    || shadow.assertExclusiveInitiatorLease !== lease
    || backup.withExclusiveInitiatorLease !== holder
    || backup.assertExclusiveInitiatorLease !== lease
    || backup.adapter !== adapter || backup.wal !== wal || backup.journal !== journal
    || branches.adapter !== adapter || branches.wal !== wal || branches.journal !== journal
    || shadow.adapter !== adapter || restart.journal !== journal
    || JSON.stringify(prepared.identity) !== JSON.stringify(id)
    || JSON.stringify(backup.identity) !== JSON.stringify(id)
    || shadow.remote.destinationPassphrase !== getSecret(id.destinationPassphraseSecretId)
    || backup.backup.passphrase !== getSecret(id.sourcePassphraseSecretId)
    || !getSecret(id.sourcePassphraseSecretId) || !getSecret(id.destinationPassphraseSecretId)) {
    throw Error("D224 requires identical fenced initiator, keys, WAL and migration identity.")
  }

  const transactionId = input.transactionId
  const originalRemote = shadow.remote
  const originalBackup = backup.backup
  const destinationSignal = originalRemote.signal
  const backupSignal = originalBackup.signal
  const repoId = branches.physicalRepositoryId
  const originalBackupBranch = frozenGithub.branchName
  const serialized = {
    identity: JSON.stringify(id),
    prepared: JSON.stringify(prepared.identity),
    backup: JSON.stringify(backup.identity),
    readiness: JSON.stringify(readiness.candidate),
    publication: JSON.stringify(branches.publication),
    settings: JSON.stringify(restart.settings),
    expected: JSON.stringify(restart.expected),
    remote: JSON.stringify({
      scope: shadow.remote.plan,
      sourceConfig: shadow.remote.sourceConfig,
      destinationConfig: shadow.remote.expectedDestinationConfig,
      receipts: shadow.remote.expectedReceipts,
      sourceTree: shadow.remote.sourceTreeSha,
      destCommit: shadow.remote.destinationCommitSha,
      fullBackup: backup.backup.plan,
      oldTree: backup.backup.expectedSourceTreeSha,
    }),
    journalKey: toBase64(key),
  }
  const sourcePassphrase = getSecret(id.sourcePassphraseSecretId)
  const destinationPassphrase = getSecret(id.destinationPassphraseSecretId)
  const methods = {
    lease: wal.assertExclusiveStageLease,
    checkpoint: wal.assertBestEffortCheckpoint,
    snapshot: journal.assertHealthySnapshot,
    read: adapter.read, exists: adapter.exists,
    write: adapter.write, mkdir: adapter.mkdir, stat: adapter.stat,
    destination: {
      repo: destinationGithub.getRepositoryIdentity,
      ref: destinationGithub.getGitRef,
      commit: destinationGithub.getGitCommit,
      tree: destinationGithub.getTreeAt,
      blob: destinationGithub.getBlob,
    },
    frozen: {
      repo: frozenGithub.getRepositoryIdentity,
      ref: frozenGithub.getGitRef,
      commit: frozenGithub.getGitCommit,
      tree: frozenGithub.getTreeAt,
      blob: frozenGithub.getBlob,
    },
    readers: (["source", "backup", "destination"] as const).map(role => {
      const r = readers[role]
      return { role, r, branch: r.branchName, identity: r.getRepositoryIdentity,
        defaultBranch: r.getRepositoryDefaultBranch, ref: r.getGitRefOrNull, commit: r.getGitCommit }
    }),
  }
  const unchanged = () => input.readiness === readiness && input.backup === backup
    && input.transactionId === transactionId
    && readiness.full === full && readiness.prepared === prepared
    && full.branches === branches && full.shadow === shadow
    && shadow.remote === originalRemote && backup.backup === originalBackup
    && branches.physicalRepositoryId === repoId
    && originalRemote.signal === destinationSignal
    && originalBackup.signal === backupSignal
    && destinationSignal?.aborted !== true && backupSignal?.aborted !== true
    && frozenGithub.branchName === originalBackupBranch
    && prepared.restart === restart && branches.identity === id
    && JSON.stringify(id) === serialized.identity
    && JSON.stringify(prepared.identity) === serialized.prepared
    && JSON.stringify(backup.identity) === serialized.backup
    && JSON.stringify(readiness.candidate) === serialized.readiness
    && JSON.stringify(branches.publication) === serialized.publication
    && JSON.stringify(restart.settings) === serialized.settings
    && JSON.stringify(restart.expected) === serialized.expected
    && JSON.stringify({
      scope: shadow.remote.plan,
      sourceConfig: shadow.remote.sourceConfig,
      destinationConfig: shadow.remote.expectedDestinationConfig,
      receipts: shadow.remote.expectedReceipts,
      sourceTree: shadow.remote.sourceTreeSha,
      destCommit: shadow.remote.destinationCommitSha,
      fullBackup: backup.backup.plan,
      oldTree: backup.backup.expectedSourceTreeSha,
    }) === serialized.remote
    && toBase64(key) === serialized.journalKey
    && prepared.journalKey === key
    && prepared.withExclusiveInitiatorLease === holder
    && branches.withExclusiveInitiatorLease === holder
    && backup.withExclusiveInitiatorLease === holder
    && branches.assertExclusiveInitiatorLease === lease
    && shadow.assertExclusiveInitiatorLease === lease
    && backup.assertExclusiveInitiatorLease === lease
    && restart.assertExclusiveInitiatorLease === lease
    && restart.indexAdapter === adapter && branches.adapter === adapter && shadow.adapter === adapter
    && backup.adapter === adapter
    && restart.wal === wal && branches.wal === wal && backup.wal === wal
    && restart.journal === journal && branches.journal === journal && backup.journal === journal
    && restart.getSecret === getSecret
    && getSecret(id.sourcePassphraseSecretId) === sourcePassphrase
    && getSecret(id.destinationPassphraseSecretId) === destinationPassphrase
    && backup.backup.passphrase === sourcePassphrase
    && shadow.remote.destinationPassphrase === destinationPassphrase
    && journal.sourceCommitSha === id.sourceCommitSha
    && journal.destinationRepoId === id.destinationRepoId
    && wal.assertExclusiveStageLease === methods.lease
    && wal.assertBestEffortCheckpoint === methods.checkpoint
    && journal.assertHealthySnapshot === methods.snapshot
    && adapter.read === methods.read && adapter.exists === methods.exists
    && adapter.write === methods.write && adapter.mkdir === methods.mkdir
    && adapter.stat === methods.stat
    && shadow.remote.github === destinationGithub && backup.backup.github === frozenGithub
    && destinationGithub.getRepositoryIdentity === methods.destination.repo
    && destinationGithub.getGitRef === methods.destination.ref
    && destinationGithub.getGitCommit === methods.destination.commit
    && destinationGithub.getTreeAt === methods.destination.tree
    && destinationGithub.getBlob === methods.destination.blob
    && frozenGithub.getRepositoryIdentity === methods.frozen.repo
    && frozenGithub.getGitRef === methods.frozen.ref
    && frozenGithub.getGitCommit === methods.frozen.commit
    && frozenGithub.getTreeAt === methods.frozen.tree
    && frozenGithub.getBlob === methods.frozen.blob
    && branches.readers === readers
    && methods.readers.every(m => {
      const r = readers[m.role]
      return m.r === r && r.branchName === m.branch
        && r.getRepositoryIdentity === m.identity
        && r.getRepositoryDefaultBranch === m.defaultBranch
        && r.getGitRefOrNull === m.ref && r.getGitCommit === m.commit
    })
  const check = async () => {
    if (!unchanged()) throw Error("D224 remote methods, migration scope or SecretStorage changed.")
    await lease()
    await methods.lease.call(wal)
    if (await methods.checkpoint.call(wal) !== "best-effort-readback-only"
      || !unchanged()) throw Error("D224 exclusive best-effort checkpoint lost.")
    const snap = await methods.snapshot.call(journal, id.walGeneration)
    if (!matchesV4ReencryptionPreparedWal(snap, id) || !unchanged()) {
      throw Error("D224 authenticated WAL no longer matches pinned Git publication.")
    }
    await assertV4ReencryptionExactSyncFence(adapter, {
      runId: id.runId, sourceRepoId: id.sourceRepoId,
      destinationRepoId: id.destinationRepoId,
    }, lease)
    if (!unchanged()) throw Error("D224 exact Sync Fence changed.")
  }
  let borrowedActive = false
  const borrowed = async <T>(body: () => Promise<T>): Promise<T> => {
    if (borrowedActive) throw Error("D224 attempted a nested initiating-device lease borrow.")
    borrowedActive = true
    try {
      await check()
      const result = await body()
      await check()
      return result
    } finally { borrowedActive = false }
  }
  const snapshotInput: V4FencedCommitPairSnapshotInput = {
    transactionId,
    readiness: {
      ...readiness,
      prepared: { ...prepared, withExclusiveInitiatorLease: borrowed },
      full: { ...full, branches: { ...branches, withExclusiveInitiatorLease: borrowed } },
    },
  }
  const backupInput: V4FencedFrozenBackupContentInput = {
    ...backup, withExclusiveInitiatorLease: borrowed,
  }
  let invoked = 0
  let completed: V4FencedLiveCandidateStageReport | V4FencedLiveIntentStageReport | null = null
  const report = await holder(async () => {
    if (++invoked !== 1) throw Error("D224 initiator lease holder invoked more than once.")
    await check()
    const firstBackup = await inspectV4FencedFrozenBackupContentAfterRestart(backupInput)
    if (firstBackup.observation !== "complete-frozen-backup-reverified-uncommitted"
      || !firstBackup.completeBackupContentReverified) {
      throw Error("D224 frozen old-key Backup content not independently verified.")
    }
    const first = await deriveV4FencedCommitPairSnapshotTestContract(snapshotInput)
    if (first.observation !== "snapshot-contract-derived-uncommitted" || !first.contract) {
      throw Error("D224 new-key Destination or local Source provenance uncertain.")
    }
    await check()
    const candidate = await stageV4ReencryptionCutoverCandidate({
      prepared: { ...prepared, withExclusiveInitiatorLease: borrowed },
      contract: first.contract,
    })
    if (candidate.status !== "production-namespace-pair-staged-uncommitted"
      || candidate.localCutoverAuthorized !== false || candidate.resumeSyncAuthorized !== false) {
      throw Error("D224 persisted Cutover candidate is incomplete.")
    }
    await check()
    const intent = persistIntent ? await stageV4ReencryptionPendingCutoverIntent({
      adapter, candidate, contract: first.contract, journalKey: key, assertHeld: check,
    }) : null
    await check()
    // Both Git content domains are revalidated AFTER every Candidate/Intent write.
    const secondBackup = await inspectV4FencedFrozenBackupContentAfterRestart(backupInput)
    const second = await deriveV4FencedCommitPairSnapshotTestContract(snapshotInput)
    if (secondBackup.observation !== "complete-frozen-backup-reverified-uncommitted"
      || secondBackup.verifiedFileCount !== firstBackup.verifiedFileCount
      || secondBackup.verifiedPlaintextBytes !== firstBackup.verifiedPlaintextBytes
      || second.observation !== "snapshot-contract-derived-uncommitted"
      || JSON.stringify(second.contract) !== JSON.stringify(first.contract)
      || !unchanged()) {
      throw Error("D224 full Backup/Destination proof changed after staged Receipt/Selector.")
    }
    await check()
    completed = Object.freeze(intent ? {
      ...candidate,
      status: intent.status, intentPath: intent.intentPath,
      provenance: "two-full-current-destination-and-frozen-backup-proofs-bracketing-write" as const,
    } : {
      ...candidate,
      provenance: "two-full-current-destination-and-frozen-backup-proofs-bracketing-write" as const,
    })
    return completed
  })
  if (invoked !== 1 || report !== completed || !unchanged()) {
    throw Error("D224 forged holder response or final migration identity drift.")
  }
  return report
}

/** D224 compatibility: stage the verified Candidate without Cutover intent. */
export function stageV4FencedLiveReencryptionCandidate(
  input: V4FencedLiveCandidateStageInput,
): Promise<V4FencedLiveCandidateStageReport> {
  return stageInternal(input, false)
}

/**
 * D227: append a domain-separated Intent under the SAME outer lease, with
 * full old/new Git proofs on both sides. The resulting record is NOT a Commit.
 */
export function stageV4FencedLiveReencryptionIntent(
  input: V4FencedLiveCandidateStageInput,
): Promise<V4FencedLiveIntentStageReport> {
  return stageInternal(input, true)
}
